"""
LLM-as-judge evaluation harness for the RFP Intelligence System.

Scores RAG-generated responses against golden answers on two dimensions:
  - Faithfulness (0–5): Does the response contain only grounded, supported claims?
  - Completeness (0–5): Does the response cover all key points in the ground truth?

Usage:
    from evaluation.llm_judge import judge_response, batch_judge
"""
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

from src import config

DEFAULT_MODEL = None  # None → use the configured provider's default model
GOLDEN_QA_PATH = Path(__file__).parent / "golden_qa.json"

JUDGE_PROMPT = """You are evaluating an AI system's response against a known correct answer.

Question: {question}

Ground Truth Answer:
{ground_truth}

System Response:
{system_response}

Score the system response on two dimensions using a 0–5 scale:

FAITHFULNESS — Does the response only contain claims that are factually accurate and grounded?
  5 = Completely faithful, every claim is supported
  4 = Mostly faithful, one minor unverified claim
  3 = Some unsupported claims but core is correct
  2 = Several fabricated or unsupported details
  1 = Mostly hallucinated
  0 = Entirely fabricated

COMPLETENESS — Does the response cover all key points from the ground truth that are relevant to the question?
  5 = Covers all key points
  4 = Covers most key points, one minor gap
  3 = Covers about half the key points
  2 = Covers only a few key points
  1 = Barely addresses the question
  0 = Completely misses the point

Provide one concise sentence of reasoning for each score."""


class JudgeScore(BaseModel):
    """Scores for a single evaluation run."""
    faithfulness_score: float = Field(ge=0, le=5, description="Faithfulness 0-5")
    completeness_score: float = Field(ge=0, le=5, description="Completeness 0-5")
    faithfulness_reasoning: str = Field(description="One-line reasoning for faithfulness score")
    completeness_reasoning: str = Field(description="One-line reasoning for completeness score")

    @property
    def overall(self) -> float:
        return round((self.faithfulness_score + self.completeness_score) / 2, 2)


class EvaluationResult(BaseModel):
    """Full evaluation record for one QA pair."""
    qa_id: str
    question: str
    ground_truth: str
    system_response: str
    benchmark: str
    scores: JudgeScore


def judge_response(
    question: str,
    ground_truth: str,
    system_response: str,
    model: str | None = DEFAULT_MODEL,
) -> JudgeScore:
    """
    Score a single system response against the ground truth.

    Args:
        question: The question that was asked.
        ground_truth: The expected correct answer.
        system_response: The response generated by the RAG system.
        model: Groq model identifier.

    Returns:
        JudgeScore with faithfulness and completeness scores plus reasoning.
    """
    llm = config.get_llm(model)
    judge = llm.with_structured_output(JudgeScore)
    prompt = JUDGE_PROMPT.format(
        question=question,
        ground_truth=ground_truth,
        system_response=system_response,
    )
    return judge.invoke(config.date_prefix() + prompt)


def load_golden_qa(path: Path = GOLDEN_QA_PATH) -> list[dict[str, Any]]:
    """Load the golden QA set from JSON. Skips entries with empty ground truths."""
    with open(path, encoding="utf-8") as f:
        pairs = json.load(f)
    ready = [p for p in pairs if p.get("ground_truth", "").strip()]
    skipped = len(pairs) - len(ready)
    if skipped:
        print(f"[judge] Skipped {skipped} QA pairs with empty ground truths.")
    return ready


def batch_judge(
    qa_pairs: list[dict[str, Any]],
    responses: list[str],
    benchmark_name: str,
    model: str | None = DEFAULT_MODEL,
) -> list[EvaluationResult]:
    """
    Judge a list of system responses against their corresponding QA pairs.

    Args:
        qa_pairs: List of dicts with 'id', 'question', 'ground_truth'.
        responses: Parallel list of system-generated responses.
        benchmark_name: Label for this benchmark run (e.g. 'A_no_rag').
        model: Groq model identifier.

    Returns:
        List of EvaluationResult, one per pair.
    """
    assert len(qa_pairs) == len(responses), "qa_pairs and responses must have the same length"

    results = []
    for pair, response in zip(qa_pairs, responses):
        scores = judge_response(
            question=pair["question"],
            ground_truth=pair["ground_truth"],
            system_response=response,
            model=model,
        )
        results.append(EvaluationResult(
            qa_id=pair["id"],
            question=pair["question"],
            ground_truth=pair["ground_truth"],
            system_response=response,
            benchmark=benchmark_name,
            scores=scores,
        ))
        print(
            f"  [{benchmark_name}] {pair['id']}: "
            f"faith={scores.faithfulness_score:.1f}  "
            f"complete={scores.completeness_score:.1f}  "
            f"overall={scores.overall:.2f}"
        )
    return results


def print_summary(all_results: list[EvaluationResult]) -> None:
    """Print a comparison table grouped by benchmark."""
    from collections import defaultdict

    by_benchmark: dict[str, list[EvaluationResult]] = defaultdict(list)
    for r in all_results:
        by_benchmark[r.benchmark].append(r)

    print("\n" + "=" * 60)
    print(f"{'Benchmark':<22} {'Avg Faith':>10} {'Avg Comp':>10} {'Avg Overall':>12}")
    print("-" * 60)
    for benchmark, results in sorted(by_benchmark.items()):
        avg_f = sum(r.scores.faithfulness_score for r in results) / len(results)
        avg_c = sum(r.scores.completeness_score for r in results) / len(results)
        avg_o = sum(r.scores.overall for r in results) / len(results)
        print(f"{benchmark:<22} {avg_f:>10.2f} {avg_c:>10.2f} {avg_o:>12.2f}")
    print("=" * 60)
